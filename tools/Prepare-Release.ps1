#Requires -Version 7.0
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$LocalAmongUsPath,
    [string]$OutputDirectory,
    [string]$CacheDirectory
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$gameRoot = (Resolve-Path -LiteralPath $LocalAmongUsPath).Path
$packaging = Join-Path $repoRoot 'packaging'
$source = Get-Content -LiteralPath (Join-Path $repoRoot 'main.cs') -Raw
$version = [regex]::Match($source, 'PluginDisplayVersion = "([^"]+)"').Groups[1].Value
$assemblyVersion = [regex]::Match($source, 'PluginVersion = "([^"]+)"').Groups[1].Value
$gameVersion = [regex]::Match($source, 'SupportedVersionAU = "([^"]+)"').Groups[1].Value
if ($version -notmatch '^[A-Za-z0-9][A-Za-z0-9.+-]*$') { throw 'Invalid release version in main.cs.' }
$dependencies = Get-Content -LiteralPath (Join-Path $packaging 'dependencies.json') -Raw | ConvertFrom-Json
if (!$OutputDirectory) { $OutputDirectory = Join-Path $repoRoot "artifacts/releases/v$version" }
if (!$CacheDirectory) { $CacheDirectory = Join-Path $repoRoot 'artifacts/release-cache' }
$OutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)
$CacheDirectory = [IO.Path]::GetFullPath($CacheDirectory)
if (Test-Path -LiteralPath $OutputDirectory) { throw 'OutputDirectory already exists. Choose a new directory to preserve existing releases.' }
if (!(Test-Path -LiteralPath (Join-Path $gameRoot 'BepInEx/interop/Assembly-CSharp.dll'))) {
    throw 'LocalAmongUsPath must have interop generated by the tested BepInEx 755 installation.'
}
$settingsPath = Join-Path $gameRoot 'Among Us_Data/globalgamemanagers'
$settingsBytes = [IO.File]::ReadAllBytes($settingsPath)
# Unity serializes the player version as a length-prefixed UTF-8 string.
# Latin1 keeps byte offsets intact while locating the game's date-version marker.
$versionMarkers = @([regex]::Matches([Text.Encoding]::Latin1.GetString($settingsBytes), '20\d{2}\.\d{1,2}\.\d{1,2}') |
    Where-Object { $_.Index -ge 4 -and [BitConverter]::ToInt32($settingsBytes, $_.Index - 4) -eq $_.Length } |
    ForEach-Object Value | Select-Object -Unique)
if ($versionMarkers.Count -ne 1 -or $versionMarkers[0] -cne $gameVersion) {
    throw "Game version marker in globalgamemanagers does not match $gameVersion."
}
$notes = Get-Content -LiteralPath (Join-Path $packaging 'RELEASE-NOTES.md') -Raw
if (!$notes.StartsWith("# TOHEE v$version`n") -and !$notes.StartsWith("# TOHEE v$version`r`n")) {
    throw 'Update packaging/RELEASE-NOTES.md for the release version in main.cs.'
}

function Get-PeInfo([string]$Path) {
    $reader = [System.Reflection.PortableExecutable.PEReader]::new([IO.File]::OpenRead($Path))
    try {
        $cor = $reader.PEHeaders.CorHeader
        return [ordered]@{
            machine = $reader.PEHeaders.CoffHeader.Machine.ToString()
            managed = ($null -ne $cor)
            ilOnly = ($null -ne $cor -and ($cor.Flags -band 1) -ne 0)
            requires32Bit = ($null -ne $cor -and ($cor.Flags -band 2) -ne 0)
        }
    } finally { $reader.Dispose() }
}

function Get-Dependency([string]$Name) {
    $entry = $dependencies.$Name
    $path = Join-Path $CacheDirectory $entry.file
    if (!(Test-Path -LiteralPath $path)) {
        Write-Host "Downloading $Name"
        Invoke-WebRequest -Uri $entry.url -OutFile $path
    }
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $entry.sha256) {
        throw "SHA256 mismatch for $Name. Cached file was retained for inspection."
    }
    return $path
}

Push-Location $repoRoot
try {
    $dirty = @(git status --porcelain=v1 --untracked-files=normal)
    if ($LASTEXITCODE -ne 0 -or $dirty.Count -ne 0) { throw 'Commit each completed stage before preparing a release.' }
    $commit = (git rev-parse HEAD).Trim()
    if ($LASTEXITCODE -ne 0) { throw 'Cannot resolve source commit.' }
    New-Item -ItemType Directory -Path $CacheDirectory -Force | Out-Null
    $runtimeArchives = @{ x64 = Get-Dependency 'bepinex-x64'; x86 = Get-Dependency 'bepinex-x86' }
    $regionDll = Get-Dependency 'region-installer'
    $work = Join-Path $repoRoot ('artifacts/release-staging/' + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $work | Out-Null
    $build = Join-Path $work 'build'
    & dotnet build (Join-Path $repoRoot 'TOHE.csproj') -c Release "-p:LocalAmongUsPath=$gameRoot" -p:PlatformTarget=AnyCPU -o $build --no-incremental
    if ($LASTEXITCODE -ne 0) { throw 'Release build failed.' }
    $dll = Join-Path $build 'TOHE.dll'
    $pluginPe = Get-PeInfo $dll
    if (!$pluginPe.managed -or !$pluginPe.ilOnly -or $pluginPe.requires32Bit) { throw 'TOHE.dll must be AnyCPU IL.' }
    if ([Reflection.AssemblyName]::GetAssemblyName($dll).Version.ToString() -ne $assemblyVersion) { throw 'Plugin assembly version mismatch.' }
    $dllHash = (Get-FileHash -LiteralPath $dll).Hash
    $packages = @()
    New-Item -ItemType Directory -Path $OutputDirectory | Out-Null
    Copy-Item -LiteralPath $dll -Destination (Join-Path $OutputDirectory 'TOHE.dll')
    foreach ($arch in @('x64', 'x86')) {
        $stage = Join-Path $work $arch
        [IO.Compression.ZipFile]::ExtractToDirectory($runtimeArchives[$arch], $stage)
        $machine = if ($arch -eq 'x64') { 'Amd64' } else { 'I386' }
        $nativeFiles = @('winhttp.dll', 'dotnet/coreclr.dll', 'dotnet/clrjit.dll')
        foreach ($file in $nativeFiles) {
            if ((Get-PeInfo (Join-Path $stage $file)).machine -ne $machine) { throw "Wrong $arch native architecture: $file" }
        }
        foreach ($file in @('BepInEx.Core.dll', 'BepInEx.Unity.Common.dll', 'BepInEx.Unity.IL2CPP.dll', 'Il2CppInterop.Common.dll', 'Il2CppInterop.Runtime.dll', 'MonoMod.Utils.dll', 'Mono.Cecil.dll', '0Harmony.dll')) {
            if ((Get-FileHash -LiteralPath (Join-Path $stage "BepInEx/core/$file")).Hash -ne
                (Get-FileHash -LiteralPath (Join-Path $gameRoot "BepInEx/core/$file")).Hash) {
                throw "Build references do not match the pinned release runtime: $file ($arch)"
            }
        }
        $plugins = Join-Path $stage 'BepInEx/plugins'
        $config = Join-Path $stage 'BepInEx/config'
        New-Item -ItemType Directory -Path $plugins, $config -Force | Out-Null
        Copy-Item -LiteralPath $dll, $regionDll -Destination $plugins
        Copy-Item -LiteralPath (Join-Path $packaging 'BepInEx.cfg'), (Join-Path $packaging 'at.duikbo.regioninstall.cfg') -Destination $config
        Copy-Item -LiteralPath (Join-Path $repoRoot 'LICENSE') -Destination (Join-Path $stage 'LICENSE.TOHEE.txt')
        $platforms = if ($arch -eq 'x64') { 'Steam / Epic Games / Microsoft Store' } else { 'itch.io' }
        $suffix = if ($arch -eq 'x64') { 'Steam-Epic-Games-Microsoft-Store_x64' } else { 'itch.io_x86' }
        if ($arch -eq 'x64') { [IO.File]::WriteAllText((Join-Path $stage 'steam_appid.txt'), "945360`n") }
        $install = (Get-Content -LiteralPath (Join-Path $packaging 'INSTALL.txt') -Raw).
            Replace('@VERSION@', $version).Replace('@GAME_VERSION@', $gameVersion).
            Replace('@ARCH@', $arch).Replace('@PLATFORMS@', $platforms).Replace('@COMMIT@', $commit)
        [IO.File]::WriteAllText((Join-Path $stage 'INSTALL-TOHEE.txt'), $install)
        $zipPath = Join-Path $OutputDirectory "TOHEE.v${version}_${suffix}.zip"
        # ZipFile includes the upstream .doorstop_version; Compress-Archive omits hidden files.
        [IO.Compression.ZipFile]::CreateFromDirectory($stage, $zipPath, [IO.Compression.CompressionLevel]::Optimal, $false)
        $archive = [IO.Compression.ZipFile]::OpenRead($zipPath)
        try {
            $names = @($archive.Entries | ForEach-Object FullName)
            foreach ($required in @('.doorstop_version', 'doorstop_config.ini', 'winhttp.dll', 'dotnet/coreclr.dll', 'BepInEx/plugins/TOHE.dll', 'BepInEx/plugins/Mini.RegionInstall.dll', 'BepInEx/config/BepInEx.cfg')) {
                if ($names -notcontains $required) { throw "Missing release file: $required" }
            }
            if ($names -match '(^|/)(interop|TOHE-DATA|Among Us_Data|requests|responses|captures)/|\.log$|RuntimeProbe|GameAssembly\.dll|Assembly-CSharp\.dll|Among Us\.exe') {
                throw 'Generated interop, game, private data or probe files found in release archive.'
            }
        } finally { $archive.Dispose() }
        $packages += [ordered]@{ file = [IO.Path]::GetFileName($zipPath); platforms = $platforms; architecture = $arch; nativeMachine = $machine; pluginSHA256 = $dllHash }
    }
    $sourceZip = Join-Path $OutputDirectory "TOHEE.v${version}_Source.zip"
    & git archive --format=zip "--prefix=TOHEE-$version/" "--output=$sourceZip" HEAD
    if ($LASTEXITCODE -ne 0) { throw 'Source archive failed.' }
    Copy-Item -LiteralPath (Join-Path $packaging 'RELEASE-NOTES.md') -Destination (Join-Path $OutputDirectory 'RELEASE-NOTES.md')
    [ordered]@{
        version = $version; assemblyVersion = $assemblyVersion; gameVersion = $gameVersion
        sourceCommit = $commit; sourceDirty = $false; builtAtUtc = [DateTime]::UtcNow.ToString('o')
        plugin = [ordered]@{ file = 'TOHE.dll'; sha256 = $dllHash; pe = $pluginPe }
        runtimeVersion = $dependencies.bepinexVersion; dependencies = $dependencies; packages = $packages
        referenceInteropSHA256 = (Get-FileHash -LiteralPath (Join-Path $gameRoot 'BepInEx/interop/Assembly-CSharp.dll')).Hash
        inputGameVersion = $versionMarkers[0]
    } | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $OutputDirectory 'release-manifest.json') -Encoding utf8NoBOM
    $checksums = Get-ChildItem -LiteralPath $OutputDirectory -File | Sort-Object Name | ForEach-Object {
        '{0}  {1}' -f (Get-FileHash -LiteralPath $_.FullName).Hash.ToLowerInvariant(), $_.Name
    }
    [IO.File]::WriteAllLines((Join-Path $OutputDirectory 'SHA256SUMS.txt'), $checksums)
    Write-Host "Release prepared: $OutputDirectory"
} finally { Pop-Location }
